def test_week_data_carries_lineups_and_source(tmp_path, monkeypatch):
    """app.py rebuilds week_data from the editable tables, which only cover
    teams and matchups. Lineups were silently dropped between pull and
    generation, losing every bench disaster."""
    lg = _league(tmp_path)
    _patch(monkeypatch, lg)
    weekly_run.run_league("sched", week=8)
    saved = memory.get_week(memory.load_league("sched"), 8)
    assert "lineups" in saved
    assert saved.get("source") == "espn_api"


